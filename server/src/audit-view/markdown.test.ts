// specs/audit-view.md AT-18 (rule 17) and AT-19 (rule 18). parseMarkdownBlocks(text) returns the
// DocBlock[] and latestTableRows(text, n) returns the AiLogState of ./schemas.ts.
import { describe, expect, it } from 'vitest';
import { AI_LOG_ROWS } from './schemas.js';
import { latestTableRows, parseMarkdownBlocks } from './markdown.js';

const text = (t: string) => ({ kind: 'text', text: t });
const code = (t: string) => ({ kind: 'code', text: t });

describe('audit-view AT-18: markdown becomes structured blocks', () => {
  // The list item's link has no angle brackets: the spec's expected output is the literal source.
  const input =
    '# Dev metrics\n\n' +
    'Generated by `npm run dev-metrics`. Do not edit by hand.\n\n' +
    '| Metric | Value |\n| --- | --- |\n| Commits | 12 (a\\|b) |\n\n' +
    '<script>alert(1)</script>\n\n' +
    '- [click](javascript:alert(1))\n\n' +
    '#### deep';

  it('AT-18: the synthetic document gives exactly the listed blocks, in order', () => {
    expect(parseMarkdownBlocks(input)).toEqual([
      { kind: 'heading', level: 1, inlines: [text('Dev metrics')] },
      {
        kind: 'paragraph',
        inlines: [
          text('Generated by '),
          code('npm run dev-metrics'),
          text('. Do not edit by hand.'),
        ],
      },
      {
        kind: 'table',
        header: [[text('Metric')], [text('Value')]],
        rows: [[[text('Commits')], [text('12 (a|b)')]]],
      },
      { kind: 'paragraph', inlines: [text('<script>alert(1)</script>')] },
      { kind: 'list', items: [[text('[click](javascript:alert(1))')]] },
      { kind: 'paragraph', inlines: [text('#### deep')] },
    ]);
  });

  it('AT-18: 600 headings give 500 blocks', () => {
    const many = Array.from({ length: 600 }, (_, i) => `## Heading ${String(i)}`).join('\n\n');
    expect(parseMarkdownBlocks(many)).toHaveLength(500);
  });

  it('AT-18: calling twice on the same input gives deep-equal output', () => {
    expect(parseMarkdownBlocks(input)).toEqual(parseMarkdownBlocks(input));
  });
});

describe('audit-view AT-19: the latest AI_LOG rows come from its log table', () => {
  const row = (i: number, cols: string[]) =>
    `| ${cols.map((c) => `${c}${String(i)}`).join(' | ')} |`;
  const rows = (cols: string[], n: number) =>
    Array.from({ length: n }, (_, i) => row(i + 1, cols)).join('\n');

  it('AT-19: 12 rows give the 4 header cells, the first 10 rows in file order and totalRows 12', () => {
    const md = `| Date | Task | Fix or rule added | Cost |\n| --- | --- | --- | --- |\n${rows(['d', 't', 'f', 'c'], 12)}\n`;
    const r = latestTableRows(md, AI_LOG_ROWS);
    expect(r).toMatchObject({ status: 'ok', totalRows: 12 });
    if (r.status !== 'ok') throw new Error('expected ok');
    expect(r.header).toEqual([
      [text('Date')],
      [text('Task')],
      [text('Fix or rule added')],
      [text('Cost')],
    ]);
    expect(r.rows).toHaveLength(10);
    expect(r.rows[0]?.[0]).toEqual([text('d1')]);
    expect(r.rows[9]?.[0]).toEqual([text('d10')]);
  });

  it('AT-19: a reordered header is still found', () => {
    const md = `| Fix or rule added | Cost | Date | Task |\n| --- | --- | --- | --- |\n${rows(['f', 'c', 'd', 't'], 2)}\n`;
    const r = latestTableRows(md, AI_LOG_ROWS);
    expect(r.status).toBe('ok');
  });

  it('AT-19: a first table without Fix or rule added is skipped for a matching second table', () => {
    const md =
      `| Date | Other |\n| --- | --- |\n| a | b |\n\n` +
      `| Date | Fix or rule added |\n| --- | --- |\n| 2026-10-01 | SECOND-TABLE |\n`;
    const r = latestTableRows(md, AI_LOG_ROWS);
    expect(r).toMatchObject({ status: 'ok', totalRows: 1 });
    if (r.status !== 'ok') throw new Error('expected ok');
    expect(JSON.stringify(r.rows)).toContain('SECOND-TABLE');
  });

  it('AT-19: no matching table gives no_table', () => {
    expect(latestTableRows('| Date | Task |\n| --- | --- |\n| a | b |\n', AI_LOG_ROWS)).toEqual({
      status: 'no_table',
    });
    expect(latestTableRows('', AI_LOG_ROWS)).toEqual({ status: 'no_table' });
  });
});
